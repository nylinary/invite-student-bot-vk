def stats_message(title: str | None, link: str | None, total: int, active: int,
                  flagged: int = 0) -> str:
    text = (
        f"📊 Твоя статистика\n"
        + (f"Вуз: {title}\n" if title else "")
        + f"\n"
        f"✅ Засчитано приглашённых: {active}\n"
        f"Это те, кто пришёл по твоей ссылке и сейчас в беседе — "
        f"по ним считается билет."
    )
    left = total - flagged - active
    details = []
    if left > 0:
        details.append(f"вышли из беседы: {left}")
    if flagged:
        details.append(f"не засчитано как накрутка: {flagged}")
    if details:
        text += f"\n\nВсего вступало по ссылке: {total} — " + ", ".join(details)
    if flagged:
        text += (
            "\nВступления пачкой в одну и ту же секунду не засчитываются — так приходят "
            "купленные аккаунты, а не друзья. Если это ошибка, напиши организатору."
        )
    if link:
        text += f"\n\n🔗 Твоя ссылка:\n{link}"
    return text


