def ticket_progress(invited: int, with_links: int) -> str:
    """Человеку до билета ещё далеко — показываем, сколько осталось."""
    from app.tickets import TIERS, next_tier

    nxt = next_tier(invited)
    lines = [
        "🎫 Билет за приглашённых",
        "",
        f"Засчитано приглашённых: {invited}",
    ]
    if with_links:
        lines.append(f"Из них уже зовут своих друзей: {with_links}")
    if nxt:
        need, name, _ = nxt
        lines += ["", f"До уровня «{name}» осталось пригласить: {need - invited}"]
    lines += [
        "",
        "Система наград:",
        *[f"{name} — от {need} приглашённых" for need, name, _ in reversed(TIERS)],
        "",
        "Кидай свою ссылку друзьям и одногруппникам — считается автоматически.",
    ]
    return "\n".join(lines)


