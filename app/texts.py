def who(user_id: int, username: str | None, full_name: str | None) -> str:
    """Кликабельное упоминание человека: [id123|@anya]. Уведомления оно не шлёт —
    сообщения уходят с disable_mentions."""
    label = f"@{username}" if username else (full_name or f"id{user_id}")
    label = label.replace("[", "(").replace("]", ")").replace("|", "/")
    return f"[id{user_id}|{label}]"


